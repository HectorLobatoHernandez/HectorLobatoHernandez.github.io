import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const base=process.env.GAZA_URL || 'http://127.0.0.1:4173';
const browser=await chromium.launch({headless:true});
try{
 const page=await browser.newPage({viewport:{width:1440,height:900}});
 const mission=await page.goto(base+'/mission-control.html?view=plant&qa=1',{waitUntil:'domcontentloaded'});
 assert.equal(mission.status(),200);
 const plant=page.frameLocator('iframe[title="GAZA Plant 3D"]');
 await plant.locator('#enterMasterFarm').waitFor({timeout:20000});
 await plant.locator('#enterMasterFarm').click();
 await page.locator('[data-pane="farm"].on').waitFor({timeout:10000});
 const farm=page.frameLocator('iframe[title*="GAZA Farm 3D"]');
 await farm.locator('#stationProcedure').waitFor({timeout:20000});
 assert.equal(await farm.locator('#steps button').count(),7);
 await farm.locator('#farmCount').fill('80');
 await farm.locator('#farmYield').fill('500');
 assert.match(await farm.locator('#farmTotal').textContent(),/40.000 litros\/día/);
 assert.match(await farm.locator('#farmTotal').textContent(),/NO ES PRODUCCIÓN REAL/);
 await page.locator('[data-view="plant"]').click();
 await plant.locator('#enterQualityLab').click();
 await page.locator('[data-pane="labs"].on').waitFor({timeout:10000});
 const labs=page.frameLocator('iframe[title*="GAZA Quality Labs"]');
 await labs.locator('#stationProcedure').waitFor({timeout:20000});
 await labs.locator('#steps button').nth(2).click();
 assert.match(await labs.locator('#stationProcedure').textContent(),/aséptica/);
 assert.equal((await labs.locator('#farmAggregate').isVisible()),false);
 await page.locator('[data-view="workflow"]').click();
 await page.locator('[data-pane="workflow"].on').waitFor({timeout:10000});
 const flow=page.frameLocator('iframe[title="GAZA End-to-End Workflow"]');
 await flow.locator('#flow .step').first().waitFor({timeout:15000});
 assert.equal(await flow.locator('#flow .step').count(),10);
 await flow.locator('#next').click();
 assert.match(await flow.locator('#state').textContent(),/FASE 2\/10/);
 console.log('GAZA spatial navigation, virtual aggregation and workflow QA passed');
}finally{await browser.close();}
